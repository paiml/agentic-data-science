library(testthat)
root <- normalizePath(testthat::test_path("..", ".."))
old <- setwd(root)
source("R/helpers.R")
source("R/locale.R")
scene <- readLines("R/locale.R")
scene_lines <- length(scene)
setwd(old)
work <- tempfile("scene")
dir.create(work)
file.copy(dir(root, full.names = TRUE), work, recursive = TRUE)
old <- setwd(work)
out <- utils::capture.output(ok <- run_scene())
txt <- paste(out, collapse = " ")
g <- jsonlite::fromJSON("data/p2.json")
d <- load_clean("data/penguins.csv")

test_that("the scene file fits the screen, 25 lines or fewer", {
  expect_lte(scene_lines, 25L)
  expect_lte(max(nchar(scene)), 59L)
})
test_that("drop_na keeps 342 rows (D14)", {
  expect_equal(nrow(d), 342L)
})
test_that("id folds move with the locale, row folds do not", {
  ids <- make_ids(nrow(d))
  f <- read_folds("data/folds.csv")
  cl <- locale_run("C", ids, d, f)
  us <- locale_run("en_US.UTF-8", ids, d, f)
  expect_equal(cl$row, g$cv_rmse$ols, tolerance = 1e-8)
  expect_equal(us$row, g$cv_rmse$ols, tolerance = 1e-8)
  moved <- all.equal(cl$by_id, us$by_id, tolerance = 1e-8)
  expect_false(isTRUE(moved))
})
test_that("the id order really differs between the locales", {
  ids <- make_ids(12)
  old <- Sys.getlocale("LC_COLLATE")
  on.exit(Sys.setlocale("LC_COLLATE", old))
  use_locale("C")
  c_order <- order(ids)
  use_locale("en_US.UTF-8")
  expect_false(identical(c_order, order(ids)))
})
test_that("fold_by_id makes 5 folds from the sorted position", {
  expect_equal(fold_by_id(c("b", "a", "c")), c(2L, 1L, 3L))
  expect_equal(sort(unique(fold_by_id(make_ids(342)))), 1:5)
})
test_that("a missing locale stops with its name", {
  old <- Sys.getlocale("LC_COLLATE")
  on.exit(Sys.setlocale("LC_COLLATE", old))
  expect_error(use_locale("xx_XX.nope"), "not installed: xx_XX")
})
test_that("locale_run restores the caller's collation", {
  old <- Sys.getlocale("LC_COLLATE")
  on.exit(Sys.setlocale("LC_COLLATE", old))
  use_locale("en_US.UTF-8")
  locale_run("C", make_ids(342), d, read_folds("data/folds.csv"))
  expect_identical(Sys.getlocale("LC_COLLATE"), "en_US.UTF-8")
})
test_that("the scene prints both CVs and reports TRUE", {
  expect_true(ok)
  expect_match(txt, "CV by row, C: +394.31296")
  expect_match(txt, "CV by row, US: 394.31296")
  expect_match(txt, "CV by id, +C: +394.9178")
  expect_match(txt, "CV by id, +US: 394.25148")
  expect_match(txt, "id folds move, row folds hold: TRUE")
})
test_that("the closed form matches the golden OLS", {
  b <- ols_closed_form(d$flipper_length_mm, d$body_mass_g)
  expect_equal(b[["slope"]], g$ols$slope, tolerance = 1e-8)
})
test_that("regression_metrics gives RMSE and R squared", {
  toy <- regression_metrics(c(1, 2, 3, 4), c(1, 2, 3, 6))
  expect_equal(toy$rmse, 1)
  expect_equal(toy$r2, 1 - 4 / 5)
})
test_that("verdict returns and prints a failure as FALSE", {
  res <- utils::capture.output(r <- verdict("x", FALSE))
  expect_false(r)
  expect_match(res, "x: FALSE")
})
