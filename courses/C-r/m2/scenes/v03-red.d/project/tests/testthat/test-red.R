library(testthat)
root <- normalizePath(testthat::test_path("..", ".."))
old <- setwd(root)
source("R/helpers.R")
source("R/red.R")
scene <- readLines("R/red.R")
scene_lines <- length(scene)
setwd(old)
work <- tempfile("scene")
dir.create(work)
file.copy(dir(root, full.names = TRUE), work, recursive = TRUE)
old <- setwd(work)
out <- utils::capture.output(ok <- run_scene())
txt <- paste(out, collapse = " ")
g <- jsonlite::fromJSON("data/p2.json")
d <- load_clean("data/penguins.csv")

test_that("the scene file fits the screen, 25 lines or fewer", {
  expect_lte(scene_lines, 25L)
  expect_lte(max(nchar(scene)), 59L)
})
test_that("drop_na keeps 342 rows (D14)", {
  expect_equal(nrow(d), 342L)
})
test_that("the true slope passes the oracle", {
  b <- ols_closed_form(d$flipper_length_mm, d$body_mass_g)
  expect_true(isTRUE(all.equal(g$ols$slope, b[["slope"]], 1e-9)))
})
test_that("a planted +1 slope bug is caught by the oracle", {
  b <- ols_closed_form(d$flipper_length_mm, d$body_mass_g)
  r <- all.equal(g$ols$slope, b[["slope"]] + 1, tolerance = 1e-9)
  expect_false(isTRUE(r))
  expect_match(r, "Mean relative difference")
})
test_that("the scene shows both slopes and a TRUE verdict", {
  expect_true(ok)
  expect_match(txt, "golden slope: 49.69")
  expect_match(txt, "broken slope: 50.69")
  expect_match(txt, "oracle caught the planted bug: TRUE")
})
test_that("verdict returns and prints a failure as FALSE", {
  res <- utils::capture.output(r <- verdict("x", FALSE))
  expect_false(r)
  expect_match(res, "x: FALSE")
})
setwd(old)
