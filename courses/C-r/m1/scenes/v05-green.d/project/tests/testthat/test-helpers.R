library(testthat)
root <- normalizePath(testthat::test_path("..", ".."))
old <- setwd(root)
if (!exists("p1_suite")) source("R/helpers.R")
raw <- read_penguins("data/penguins.csv")
clean <- na_policy(raw)

test_that("checksums verify and a changed byte fails", {
  expect_true(check_sums("data"))
  bad <- tempfile("bad")
  dir.create(bad)
  file.copy(list.files("data", full.names = TRUE), bad)
  cat("x", file = file.path(bad, "penguins.csv"), append = TRUE)
  expect_false(check_sums(bad))
})
test_that("read_penguins gives 344 typed rows", {
  expect_equal(nrow(raw), 344)
  expect_type(raw$body_mass_g, "double")
  expect_type(raw$year, "integer")
})
test_that("na_policy keeps measurements complete, sex untouched", {
  expect_equal(nrow(clean), 342)
  expect_false(anyNA(clean[numeric_cols]))
  expect_equal(sum(is.na(clean$sex)), 9)
})
test_that("summarise_by_species and summary_json match gold", {
  s <- summarise_by_species(clean)
  expect_equal(s$n, c(151L, 68L, 123L))
  doc <- jsonlite::fromJSON(as.character(summary_json(s)))
  gold <- jsonlite::fromJSON("data/p1.json")
  expect_equal(unlist(doc), unlist(gold), tolerance = 1e-9)
})
test_that("count_species tallies the three species", {
  want <- c(Adelie = 151, Chinstrap = 68, Gentoo = 123)
  expect_equal(count_species(clean), want)
})
test_that("verdict prints both outcomes and returns them", {
  out <- utils::capture.output(r <- verdict("x: ", FALSE))
  expect_false(r)
  expect_match(out, "x: FALSE")
  out <- utils::capture.output(r <- verdict("x: ", TRUE))
  expect_true(r)
  expect_match(out, "x: TRUE")
})
test_that("p1_suite: green, red for no-op policy, population sd", {
  expect_true(all(p1_suite()))
  noop <- function(df) dplyr::filter(df, TRUE)
  expect_equal(sum(!p1_suite(policy = noop)), 3)
  pop <- function(x) sqrt(mean((x - mean(x))^2))
  expect_equal(sum(!p1_suite(sd_fn = pop)), 2)
})
setwd(old)
